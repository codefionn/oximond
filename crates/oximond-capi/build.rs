fn main() {
    if std::env::var_os("CARGO_FEATURE_BUNDLED_BRIDGE").is_none() {
        return;
    }
    println!("cargo:rerun-if-changed=bridge.cpp");
    println!("cargo:rerun-if-changed=auxiliary.cpp");
    let version = ["52", "53", "54", "55"]
        .into_iter()
        .find(|version| std::env::var_os(format!("CARGO_FEATURE_LUA{version}")).is_some())
        .unwrap_or("51");
    let vendor = format!("vendor/lua{version}");
    println!("cargo:rerun-if-changed={vendor}");
    let mut build = cc::Build::new();
    build
        .cpp(true)
        .std("c++17")
        .include(&vendor)
        .file("bridge.cpp")
        .file("auxiliary.cpp")
        .warnings(false);
    if std::env::var_os("CARGO_FEATURE_LAZY_BRIDGE").is_some() {
        // A shared object, so it links the same libstdc++.so as the C++ modules it hosts and
        // exceptions crossing the bridge stay in one runtime. src/lazy_bridge.rs embeds it.
        let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
        let target = out.join("liboximond_bridge.so");
        let mut command = build.pic(true).get_compiler().to_command();
        command
            .args(["-shared", "-fPIC", "-DOXIMOND_LAZY_BRIDGE", "-o"])
            .arg(&target);
        command.args(["bridge.cpp", "auxiliary.cpp", "-ldl"]);
        let status = command.status().expect("run the C++ compiler");
        assert!(
            status.success(),
            "building the native bridge shared object failed"
        );
        return;
    }
    // The DLL's thunks are x86-64 assembly for a MinGW-style compiler.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("gnu")
        && std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64")
    {
        let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
        lua_dll(&vendor, version, &out);
        build.include(&out).define("OXIMOND_LUA_DLL", None);
    }
    build.compile("oximond_native_bridge");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        println!("cargo:rustc-link-lib=dl");
    }
}

/// Builds the `lua51.dll` (or `lua54.dll`, and so on) that Windows modules
/// import the Lua API from. A module names the DLL its import library came
/// from, and the loader binds it to a loaded module of that name. The DLL
/// holds one thunk per API function, each a jump through a slot that the
/// executable fills with its own function's address. `bridge.cpp` embeds the
/// DLL, writes it to a per-user cache directory, and loads and binds it before
/// the first native module. Generated into `out`: `lua_dll_bytes.inc` (the
/// DLL and its names), `lua_dll_table.inc` (the executable's addresses, in
/// thunk order), the DLL source, the DLL, and a module definition file
/// (`lua51.def`) that `scripts/ci.sh windows` makes the import library for its
/// test module from.
fn lua_dll(vendor: &str, version: &str, out: &std::path::Path) {
    use std::fmt::Write;
    let names = api_names(vendor);
    let mut source = String::from(
        "/* Generated by oximond-capi/build.rs: see lua_dll there. */\n\
         void *oximond_lua_slots[NAMES];\n\
         __declspec(dllexport) void oximond_lua_bind(void *const *table)\n\
         {\n    for (int i = 0; i < NAMES; i++) oximond_lua_slots[i] = table[i];\n}\n\
         int __stdcall oximond_lua_entry(void *module, unsigned long reason, void *reserved)\n\
         {\n    (void)module; (void)reason; (void)reserved;\n    return 1;\n}\n\
         __asm__(\n    \".text\\n\"\n",
    )
    .replace("NAMES", &names.len().to_string());
    for (index, name) in names.iter().enumerate() {
        let _ = writeln!(
            source,
            "    \".globl {name}\\n.def {name}; .scl 2; .type 32; .endef\\n\"\n    \"{name}: jmpq *oximond_lua_slots+{}(%rip)\\n\"",
            index * 8
        );
    }
    source.push_str("    \".section .drectve,\\\"yn\\\"\\n\"\n");
    for name in &names {
        let _ = writeln!(source, "    \".ascii \\\" -export:{name}\\\"\\n\"");
    }
    source.push_str(");\n");
    let c = out.join("lua_dll.c");
    std::fs::write(&c, source).expect("write the Lua DLL source");
    let dll = out.join(format!("lua{version}.dll"));
    let mut command = cc::Build::new()
        .cargo_metadata(false)
        .get_compiler()
        .to_command();
    command
        .args(["-shared", "-nostdlib", "-O2", "-g0"])
        .arg("-Wl,--entry=oximond_lua_entry")
        .arg("-o")
        .arg(&dll)
        .arg(&c);
    let status = command.status().expect("run the C compiler");
    assert!(status.success(), "building the Lua DLL failed");
    let bytes = std::fs::read(&dll).expect("read the Lua DLL");

    // FNV-1a names the cache directory, so a changed DLL gets a new one.
    let hash = bytes.iter().fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x0100_0000_01b3)
    });
    let dotted = format!("{}.{}", &version[..1], &version[1..]);
    let mut include = format!(
        "static const wchar_t *const lua_dll_names[] = {{L\"lua{version}.dll\", L\"lua{dotted}.dll\"}};\n\
         static const wchar_t lua_dll_cache[] = L\"oximond-lua{version}-{hash:016x}\";\n\
         static const unsigned char lua_dll_bytes[] = {{"
    );
    for (index, byte) in bytes.iter().enumerate() {
        if index % 24 == 0 {
            include.push('\n');
        }
        let _ = write!(include, "{byte},");
    }
    include.push_str("\n};\n");
    std::fs::write(out.join("lua_dll_bytes.inc"), include).expect("write lua_dll_bytes.inc");
    let table: String = names
        .iter()
        .map(|name| format!("reinterpret_cast<void *>(&{name}),\n"))
        .collect();
    std::fs::write(out.join("lua_dll_table.inc"), table).expect("write lua_dll_table.inc");
    let mut def = format!("LIBRARY lua{version}.dll\nEXPORTS\n");
    for name in &names {
        let _ = writeln!(def, "    {name}");
    }
    std::fs::write(out.join(format!("lua{version}.def")), def).expect("write the .def file");
}

/// The API functions the headers in `vendor` declare and this crate defines,
/// in Rust (`src/lib.rs`), in `bridge.cpp` or in the vendored C files. A
/// declared function that nothing defines (Luanti's `lua_atccall`) is left out.
fn api_names(vendor: &str) -> Vec<String> {
    let read = |path: &str| std::fs::read_to_string(path).unwrap_or_default();
    let luaconf = read(&format!("{vendor}/luaconf.h"));
    let mut names = Vec::new();
    for header in ["lua.h", "lauxlib.h", "lualib.h"] {
        // Whether each open `#if` hides its lines: a `LUA_COMPAT_` switch that
        // luaconf.h does not define, as `LUA_COMPAT_GETN` in Lua 5.1.
        let mut hidden: Vec<bool> = Vec::new();
        for line in read(&format!("{vendor}/{header}")).lines() {
            let directive = line.trim_start();
            if directive.starts_with("#if") {
                let switch = directive
                    .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .find(|word| word.starts_with("LUA_COMPAT_"));
                hidden.push(switch.is_some_and(|switch| {
                    !luaconf.lines().any(|line| {
                        line.trim_start()
                            .strip_prefix("#define")
                            .is_some_and(|rest| rest.split_whitespace().next() == Some(switch))
                    })
                }));
                continue;
            }
            if directive.starts_with("#else") || directive.starts_with("#elif") {
                if let Some(top) = hidden.last_mut() {
                    *top = !*top;
                }
                continue;
            }
            if directive.starts_with("#endif") {
                hidden.pop();
                continue;
            }
            if hidden.contains(&true) || !line.starts_with("LUA") || !line.contains("_API") {
                continue;
            }
            let Some(name) = declared_name(line) else {
                continue;
            };
            if !names.contains(&name) {
                names.push(name);
            }
        }
    }
    let rust = read("src/lib.rs");
    let mut c = read("bridge.cpp");
    for file in std::fs::read_dir(vendor).expect("read the vendored Lua directory") {
        let path = file.expect("list the vendored Lua directory").path();
        if path.extension().is_some_and(|extension| extension == "c") {
            c.push_str(&std::fs::read_to_string(&path).unwrap_or_default());
        }
    }
    names.retain(|name| {
        rust.contains(&format!("fn {name}("))
            || rust.contains(&format!("fn {name}<"))
            || c.lines().any(|line| {
                !line.starts_with([' ', '\t', '#', '/', '*'])
                    && !line.trim_end().ends_with(';')
                    && declared_name(line).as_deref() == Some(name.as_str())
            })
    });
    names
}

/// The function name in a declaration or definition line: the identifier
/// before the parameter list, with or without the parentheses Lua's
/// headers put around it.
fn declared_name(line: &str) -> Option<String> {
    let mut name = None;
    let bytes = line.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index].is_ascii_alphabetic() || bytes[index] == b'_' {
            let start = index;
            while index < bytes.len()
                && (bytes[index].is_ascii_alphanumeric() || bytes[index] == b'_')
            {
                index += 1;
            }
            let word = &line[start..index];
            let rest = line[index..].trim_start();
            let rest = rest.strip_prefix(')').map_or(rest, str::trim_start);
            // `lua_Number (lua_tonumber) (...)`: a type is capitalized after
            // its prefix, a function is not.
            let function = ["lua_", "luaL_", "luaopen_"].iter().any(|prefix| {
                word.strip_prefix(prefix)
                    .is_some_and(|tail| tail.starts_with(|c: char| c.is_ascii_lowercase()))
            });
            if rest.starts_with('(') && function {
                name = Some(word.to_owned());
                break;
            }
        } else {
            index += 1;
        }
    }
    name
}
