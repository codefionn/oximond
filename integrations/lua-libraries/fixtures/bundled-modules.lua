local cjson = require("cjson")
local safe = require("cjson.safe")
local struct = require("struct")
local cmsgpack = require("cmsgpack")
local cmsgpack_safe = require("cmsgpack_safe")
local function hex(bytes)
   return (bytes:gsub(".", function(char) return string.format("%02x", string.byte(char)) end))
end
local decoded = cjson.decode('{"nested":{"values":[true,false,null,42]},"text":"a\\u0000b","unicode":"\\u03bb"}')
assert(decoded.nested.values[1] == true and decoded.nested.values[2] == false)
assert(decoded.nested.values[3] == cjson.null and decoded.nested.values[4] == 42)
assert(decoded.text == "a\0b" and decoded.unicode == "\206\187")
assert(cjson.decode(cjson.encode(decoded)).text == decoded.text)
assert(cjson.encode({true, false, cjson.null, "a\0b"}) == '[true,false,null,"a\\u0000b"]')
assert(cjson.encode_number_precision(10) == 10)
assert(cjson.encode(1.25) == "1.25")
assert(cjson.encode_number_precision(14) == 14)
local isolated = cjson.new()
assert(isolated.encode_number_precision(8) == 8)
assert(cjson.encode_number_precision() == 14)
local invalid, decode_error = safe.decode("{broken")
assert(invalid == nil and type(decode_error) == "string")
local cycle = {}
cycle[1] = cycle
local encoded, encode_error = safe.encode(cycle)
assert(encoded == nil and type(encode_error) == "string")
assert(not pcall(cjson.encode, cycle))
cjson.encode_sparse_array(false, 2, 2)
assert(not pcall(cjson.encode, {[1] = "a", [10] = "b"}))
cjson.encode_sparse_array(false, 2, 10)
cjson.encode_number_precision(8)
package.loaded.cjson = nil
local reloaded = require("cjson")
assert(reloaded ~= cjson and reloaded.null == cjson.null)
assert(reloaded.encode_number_precision() == 14 and cjson.encode_number_precision() == 8)
print("cjson recursive null settings unicode binary safe ok")
local bytes = struct.pack(">I2i2c3s", 0x1234, -2, "A\0B", "x")
assert(hex(bytes) == "1234fffe4100427800")
assert(struct.size(">I2i2c3") == 7)
local unsigned, signed, fixed, terminated, next_position = struct.unpack(">I2i2c3s", bytes)
assert(unsigned == 0x1234 and signed == -2 and fixed == "A\0B" and terminated == "x")
assert(next_position == #bytes + 1)
local little = struct.pack("<I4", 0x12345678)
assert(hex(little) == "78563412")
assert(not pcall(struct.unpack, ">I4", "\0"))
print("struct", hex(bytes), hex(little))
local packed = cmsgpack.pack({true, "a\0b", -129})
assert(hex(packed) == "93c3a3610062d1ff7f")
local values = cmsgpack.unpack(packed)
assert(values[1] == true and values[2] == "a\0b" and values[3] == -129)
assert(hex(cmsgpack.pack(1099511627776)) == "cf0000010000000000")
local object = cmsgpack.unpack(cmsgpack.pack({text = "binary\0", nested = {1, 2}}))
assert(object.text == "binary\0" and object.nested[2] == 2)
assert(not pcall(cmsgpack.unpack, "\217"))
local truncated, truncated_err = cmsgpack_safe.unpack("\217")
assert(truncated == nil and type(truncated_err) == "string")
print("cmsgpack", hex(packed), hex(cmsgpack.pack(1099511627776)))
