local tl = require("tl")
local fd = assert(io.open(TEAL_SOURCE, "rb"))
local input = assert(fd:read("*a"))
fd:close()
local function self_compile(compiler)
   local env = assert(compiler.init_env(false, "optional", "5.1"))
   local result = assert(compiler.process_string(input, false, env, "tl.tl"))
   assert(#result.syntax_errors == 0)
   assert(#result.type_errors == 0, result.type_errors[1] and result.type_errors[1].msg)
   return assert(compiler.pretty_print_ast(result.ast, "5.1"))
end
-- Match upstream's two-pass selfbuild, including the compiler's own typecheck.
local generated = self_compile(tl)
local compiler = assert((loadstring or load)(generated, "@bootstrap-tl.lua"))()
assert(type(compiler) == "table" and compiler.version() == tl.version())
assert(self_compile(compiler) == generated)
local result = compiler.process_string("local answer: number = 42\nreturn answer\n", false,
   assert(compiler.init_env(false, "off", "5.1")), "bootstrap-fixture.tl")
assert(#result.syntax_errors == 0 and #result.type_errors == 0)
local code = assert(compiler.pretty_print_ast(result.ast, "5.1"))
assert(assert((loadstring or load)(code))() == 42)
-- Bytes generated by the real compiler are compared against the matching runtime.
local out = assert(io.open("bootstrap-tl.lua", "wb"))
assert(out:write(generated))
out:close()
print("teal compiler self bootstrap", #generated)
