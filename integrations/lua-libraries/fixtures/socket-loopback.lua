local socket = require("socket")
local mime = require("mime")
local server = assert(socket.bind("127.0.0.1", 0))
assert(server:settimeout(2))
local address, port = server:getsockname()
assert(address == "127.0.0.1" and tonumber(port) > 0)
local client = assert(socket.tcp())
assert(client:settimeout(2))
assert(client:connect(address, port))
local peer = assert(server:accept())
assert(peer:settimeout(2))
local binary = "tcp\0payload\255\r\n"
assert(client:send(binary) == #binary)
assert(peer:receive(#binary) == binary)
assert(peer:send("part\0") == 5)
assert(client:settimeout(0))
local data, err, partial = client:receive(10)
assert(data == nil and err == "timeout" and partial == "part\0")
assert(peer:send("tail!") == 5)
assert(client:settimeout(2))
assert(client:receive(10, partial) == "part\0tail!")
assert(peer:send("line\r\n") == 6)
assert(client:receive("*l") == "line")
local read, written = peer:getstats()
assert(read == #binary and written == 16)
peer:close()
local closed, close_err = client:receive(1)
assert(closed == nil and close_err == "closed")
client:close()
server:close()
local udp_server = assert(socket.udp())
assert(udp_server:setsockname("127.0.0.1", 0))
assert(udp_server:settimeout(2))
local udp_address, udp_port = udp_server:getsockname()
local udp_client = assert(socket.udp())
assert(udp_client:setpeername(udp_address, udp_port))
assert(udp_client:send(binary) == #binary)
local received, remote_address, remote_port = udp_server:receivefrom()
assert(received == binary and remote_address == "127.0.0.1" and tonumber(remote_port) > 0)
assert(udp_server:sendto("reply\0", remote_address, remote_port) == 6)
assert(udp_client:settimeout(2))
assert(udp_client:receive() == "reply\0")
assert(udp_client:settimeout(0))
local empty, timeout_err = udp_client:receive()
assert(empty == nil and timeout_err == "timeout")
udp_server:close()
udp_client:close()
assert(mime.unb64(mime.b64(binary)) == binary)
local guarded = socket.protect(function()
   local try = socket.newtry(function() end)
   return try(nil, "fixture error")
end)
local value, guarded_err = guarded()
assert(value == nil and guarded_err == "fixture error")
print("socket tcp udp partial timeout binary mime exceptions ok")
